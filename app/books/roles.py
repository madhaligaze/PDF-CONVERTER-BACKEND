"""Роли: чего приложению не хватает, чтобы считать.

Вторая половина «разговора двух сторон». `discover` рассказывает, что есть в
книге; здесь объявлено, что нужно продукту. Между ними встаёт привязка — и она
единственное, что специфично для компании.

Почему роли объявляет продукт, а не арендатор
─────────────────────────────────────────────
Дебиторке нужно знать, где сумма договора, где оплачено и где сальдо. Это не
зависит от того, чья книга: другая компания ведёт те же величины под другими
названиями. Меняются названия — не смысл. Поэтому роль общая, а привязка
названия к роли — своя у каждого.

Ровно отсюда следует и главное свойство раздела: чтобы подключить новую
компанию, не нужно писать код. Нужно разложить её колонки по этим гнёздам.

Почему разделы объявлены здесь, а не в базе
───────────────────────────────────────────
Раздел — функция приложения. Дебиторка умеет считать долг, потому что её так
написали, а не потому что кто-то завёл строку в таблице. Арендатор не может
изобрести раздел, и хранить требования разделов как настройку значило бы
сделать вид, что может.

Обратное тоже верно и важнее: список `SECTIONS` — это обещание. Если раздел
просит роль, он обязан её использовать; если использует — обязан просить. Иначе
на табло привязок человек увидит зелёный раздел, который на самом деле не
считается, или будет искать поле, которое никому не нужно.

Про синонимы
────────────
`synonyms` — написания заголовка, по которым роль узнаётся сама. Взяты из
книг BBC, но это не привязка к компании: так эти величины называют в русской
финансовой практике вообще. Каталог со временем умнеет — подтверждённые
человеком привязки становятся выученными синонимами (`books.role_synonyms`),
и следующая книга с тем же названием колонки привяжется без вопросов.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Role:
    """Гнездо: величина, которую продукт умеет считать."""

    key: str
    title: str
    value_type: str
    description: str = ""
    #: Написания заголовка, по которым роль узнаётся автоматически.
    synonyms: tuple[str, ...] = ()


@dataclass(frozen=True)
class Section:
    """Раздел приложения и то, без чего он не считается."""

    key: str
    title: str
    #: Нет хотя бы одной — раздел не считается вовсе.
    required: tuple[str, ...]
    #: Есть — считает точнее; нет — обходится.
    optional: tuple[str, ...] = ()



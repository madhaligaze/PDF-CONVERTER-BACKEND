# ── Доступ ───────────────────────────────────────────────────────────────────

_BY_KEY: dict[str, Role] = {item.key: item for item in ROLES}
_SECTION_BY_KEY: dict[str, Section] = {item.key: item for item in SECTIONS}


def role(key: str) -> Role | None:
    return _BY_KEY.get(key)


def all_roles() -> tuple[Role, ...]:
    return ROLES


def sections() -> tuple[Section, ...]:
    return SECTIONS


@dataclass(frozen=True)
class SectionStatus:
    """Что с разделом при текущих привязках — середина табло.

    Именно это человек читает, разложив колонки по гнёздам: не «привязано 12
    полей», а «дебиторка считается, календарю не хватает даты окончания
    периода». Раздел, которому не хватает роли, показывает, чего не хватает, —
    и не показывает ноль.
    """

    key: str
    title: str
    computes: bool
    required: tuple[str, ...]
    missing_required: tuple[str, ...]
    missing_optional: tuple[str, ...]

    @property
    def missing_titles(self) -> tuple[str, ...]:
        return tuple(
            _BY_KEY[key].title for key in self.missing_required if key in _BY_KEY
        )

    @property
    def bound_required(self) -> int:
        """Сколько обязательных ролей раздел получил именно из этой книги.

        Отличает «раздел сломан» от «раздел не про эту книгу», а это разные
        вещи, и путать их дорого. Журнал операций не содержит ни заказчика, ни
        суммы договора — и не должен: дебиторка считается из мастер-книги. Пока
        табло об этом не знало, оно писало над журналом «Дебиторка — не хватает
        Заказчик, Сумма договора, Сальдо конец», и экран читался как три
        сломанных раздела там, где всё в порядке.
        """
        return len(self.required) - len(self.missing_required)

    def to_dict(self) -> dict[str, object]:
        return {
            "key": self.key,
            "title": self.title,
            "computes": self.computes,
            "required": list(self.required),
            "bound_required": self.bound_required,
            "missing_required": list(self.missing_required),
            "missing_optional": list(self.missing_optional),
            "missing_titles": list(self.missing_titles),
        }


def section_status(bound_roles: set[str] | frozenset[str]) -> list[SectionStatus]:
    """Состояние всех разделов при данном наборе привязанных ролей."""
    result: list[SectionStatus] = []
    for item in SECTIONS:
        missing_required = tuple(key for key in item.required if key not in bound_roles)
        missing_optional = tuple(key for key in item.optional if key not in bound_roles)
        result.append(
            SectionStatus(
                key=item.key,
                title=item.title,
                computes=not missing_required,
                required=item.required,
                missing_required=missing_required,
                missing_optional=missing_optional,
            )
        )
    return result


def roles_wanted_by_sections() -> tuple[str, ...]:
    """Роли, которые хоть кто-то просит. Порядок — как в каталоге."""
    wanted: set[str] = set()
    for item in SECTIONS:
        wanted.update(item.required)
        wanted.update(item.optional)
    return tuple(item.key for item in ROLES if item.key in wanted)


